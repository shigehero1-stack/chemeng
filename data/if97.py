def region1(T, p):
    pi, tau = p / 16.53, 1386.0 / T
    g = gp = gt = 0.0
    for I, J, n in R1:
        a, b = 7.1 - pi, tau - 1.222
        g += n * a ** I * b ** J
        gp += -n * I * a ** (I - 1) * b ** J
        gt += n * a ** I * J * b ** (J - 1)
    v = pi * gp * R * T / p / 1000
    h = tau * gt * R * T
    s = (tau * gt - g) * R
    return v, h, s


def region2(T, p):
    pi, tau = p, 540.0 / T
    g0 = math.log(pi) + sum(n * tau ** J for J, n in R2_0)
    g0p = 1 / pi
    g0t = sum(n * J * tau ** (J - 1) for J, n in R2_0)
    gr = grp = grt = 0.0
    for I, J, n in R2_r:
        b = tau - 0.5
        gr += n * pi ** I * b ** J
        grp += n * I * pi ** (I - 1) * b ** J
        grt += n * pi ** I * J * b ** (J - 1)
    v = pi * (g0p + grp) * R * T / p / 1000
    h = tau * (g0t + grt) * R * T
    s = (tau * (g0t + grt) - (g0 + gr)) * R
    return v, h, s


def psat(T):
    th = T + N4[9] / (T - N4[10])
    A = th * th + N4[1] * th + N4[2]
    B = N4[3] * th * th + N4[4] * th + N4[5]
    C = N4[6] * th * th + N4[7] * th + N4[8]
    return (2 * C / (-B + math.sqrt(B * B - 4 * A * C))) ** 4


def tsat(p):
    be = p ** 0.25
    E = be * be + N4[3] * be + N4[6]
    F = N4[1] * be * be + N4[4] * be + N4[7]
    G = N4[2] * be * be + N4[5] * be + N4[8]
    D = 2 * G / (-F - math.sqrt(F * F - 4 * E * G))
    return (N4[10] + D - math.sqrt((N4[10] + D) ** 2 - 4 * (N4[9] + N4[10] * D))) / 2


def saturation(T):
    """飽和状態の値。領域1・2を使うので 273.16 K〜623.15 K（350 °C）まで。"""
    p = psat(T)
    vf, hf, sf = region1(T, p)
    vg, hg, sg = region2(T, p)
    return dict(T=T, p=p, vf=vf, vg=vg, hf=hf, hg=hg, hfg=hg - hf, sf=sf, sg=sg)


